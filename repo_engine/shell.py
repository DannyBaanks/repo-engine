def read_marker(repo: Path) -> dict:
    marker = repo / ".repo-engine.toml"
    if not marker.exists():
        raise RuntimeError(f"no .repo-engine.toml in {repo}")
    with open(marker, "rb") as f:
        return tomllib.load(f).get("repo_engine", {})


def artifact_status(repo: Path, required: list[str]) -> list[dict]:
    results = []
    for name in required:
        path = repo / name
        if name == "demo":
            present = path.is_dir() and any(path.iterdir()) if path.is_dir() else False
        elif name == ".github/workflows":
            present = path.is_dir()
        else:
            present = path.is_file()
        results.append({"name": name, "present": present})
    return results


