def _artifact_li(a: dict) -> str:
    cls = "check" if a["present"] else "miss"
    icon = "&#10003;" if a["present"] else "&#10007;"
    if a["present"]:
        name = f"<code>{a['name']}</code>"
    else:
        name = f'<span class="placeholder">{a["name"]} missing</span>'
    return f'<li><span class="{cls}">{icon}</span> {name}</li>'


def _scan_summary(repo: Path) -> dict:
    try:
        findings = audit.analyze(repo)
        crit = sum(1 for f in findings if f.severity == "critical")
        warn = sum(1 for f in findings if f.severity == "warning")
        info = sum(1 for f in findings if f.severity == "info")
        return {
            "critical": crit,
            "warning": warn,
            "info": info,
            "total": len(findings),
        }
    except Exception:  # noqa: BLE001
        return {"critical": 0, "warning": 0, "info": 0, "total": 0}


def render_dashboard(repo: Path, marker: dict, template: dict) -> str:
    artifacts = artifact_status(repo, template.get("required_artifacts", []))
    checks = template.get("release_checks", [])
    phase = marker.get("phase", "building")
    phase_class = "ready" if phase == "released" else "building"
    title = repo.name.replace("-", " ").replace("_", " ").title()
    artifact_items = "\n".join(_artifact_li(a) for a in artifacts)
    check_items = "\n".join(f"<li><code>{c}</code></li>" for c in checks)

    summary = _scan_summary(repo)
    crit_count = summary["critical"]
    warn_count = summary["warning"]
    info_count = summary["info"]
    crit_color = SEVERITY_COLOR["critical"] if crit_count else "#8b949e"
    warn_color = SEVERITY_COLOR["warning"] if warn_count else "#8b949e"
    info_color = SEVERITY_COLOR["info"] if info_count else "#8b949e"

    return DASHBOARD_HTML.format(
        title=title,
        phase=phase,
        phase_class=phase_class,
        template=template.get("label", template.get("id", "")),
        visual=template.get("visual_language", ""),
        artifact_items=artifact_items,
        check_items=check_items,
        repo_name=repo.name,
        last_scan=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
        timestamp=datetime.now(timezone.utc).isoformat(timespec="seconds"),
        crit_count=crit_count,
        warn_count=warn_count,
        info_count=info_count,
        crit_color=crit_color,
        warn_color=warn_color,
        info_color=info_color,
    )


def package(repo: Path) -> Path:
    marker = read_marker(repo)
    template_id = marker.get("template", "")
    templates = all_templates()
    template = templates.get(template_id, {})
    if not template:
        raise RuntimeError(f"unknown template '{template_id}'")

    demo_dir = repo / "demo"
    demo_dir.mkdir(exist_ok=True)
    out = demo_dir / "index.html"
    out.write_text(render_dashboard(repo, marker, template), encoding="utf-8")
    return out
